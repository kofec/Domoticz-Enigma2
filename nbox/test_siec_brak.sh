#!/bin/sh
#
# Testy SIEC-BRAK, DHCP=auto i dhcp_od_nowa z nbox_monitor.sh - na atrapach,
# bez boxa. Funkcje monitora sa wczytywane do tego samego procesu (wszystko
# przed "# --- Start"), a czas, ip, ping, logger, Domoticz i akcje to funkcje
# powloki - na Windows kazdy osobny program to dziesiatki ms.
#
#   dash nbox/test_siec_brak.sh        (albo busybox sh / bash --posix)
#
# Wynik: linie ZLE przy bledach, na koncu podsumowanie; kod 1 = cos nie przeszlo.

D=$(cd "$(dirname "$0")" && pwd)
T=$(mktemp -d) || exit 1
trap 'rm -rf "$T"' EXIT

# Bez CR - checkout na Windows z core.autocrlf=true
sed -e 's/\r$//' -e '/^# --- Start/,$d' "$D/nbox_monitor.sh" > "$T/lib.sh"

NAZWA=test RAM_DIR="$T" PROBKI_MAX=10
# shellcheck source=/dev/null
. "$T/lib.sh"

# --- Atrapy -------------------------------------------------------------------

T_UP=0; T_IP_ADDR=""; T_IP_ROUTE=""; T_PING=""; T_DHCP_DZIALA=0; T_DZ_RC=0
ZD=""; AKCJE=""; POW=""; WYWOLANIA=""

uptime_s() { echo "$T_UP"; }
stempel()  { echo "2026-10-17 07:52:00"; }
date() {
    case "$1" in
        +%H:%M)    echo 07:52 ;;
        +%H:%M:%S) echo 07:52:00 ;;
        +%Y)       echo 2026 ;;
        *)         echo 20261017_075200 ;;
    esac
}
# zdarzenie() i ekran_log() wolaja logger - tu zbieramy zdarzenia
logger() { ZD="$ZD|$3"; }
ip() {
    case "$*" in
        "-4 addr show dev $SIEC_DEV") printf '%s' "$T_IP_ADDR" ;;
        route)                        printf '%s' "$T_IP_ROUTE" ;;
    esac
}
ping1() { case " $T_PING " in *" $1 "*) return 0 ;; esac; return 1; }
dhcp_dziala() { [ "$T_DHCP_DZIALA" -eq 1 ]; }
dz_notify() { POW="$POW|$1#$2"; return "$T_DZ_RC"; }

ADRES_OK='2: eth0: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1500 qdisc pfifo_fast qlen 1000
    inet 192.168.3.11/24 brd 192.168.3.255 scope global eth0'
ADRES_BRAK='2: eth0: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1500 qdisc pfifo_fast qlen 1000'
TRASA_OK='192.168.3.0/24 dev eth0 scope link  src 192.168.3.11
default via 192.168.3.1 dev eth0'
TRASA_BEZ_DEFAULT='192.168.3.0/24 dev eth0 scope link  src 192.168.3.11'

ok=0; zle=0
sprawdz() {
    if eval "$2"; then ok=$((ok + 1))
    else zle=$((zle + 1)); echo "ZLE: $1"; echo "     warunek: $2"; echo "     ZD=$ZD AKCJE=$AKCJE POW=$POW"
    fi
}
zawiera() { case "$1" in *"$2"*) return 0 ;; esac; return 1; }
ile() {   # ile razy $2 w $1
    _n=0; _r="$1"
    while :; do case "$_r" in *"$2"*) _n=$((_n + 1)); _r="${_r#*"$2"}" ;; *) break ;; esac; done
    echo "$_n"
}

# Stan monitora od nowa (zmienne z nbox_monitor.sh)
od_nowa() {
    sb_od=""; sb_od_godz=""; sb_zgl=0; sb_ost=""; sb_napraw=0
    naprawa_ost=""; siec_zla_od=""; czyt_od=""; czyt_zgloszony=0; czyt_ok=0
    zd_liczba=0; zd_wazne=""; zd_wazny_txt=""; pow_inne=""; pow_siec=""; zal_temat=""
    ZD=""; AKCJE=""; POW=""; tuner=0
    SIEC_BRAK_PO=300; SIEC_BRAK_CO=300; REBOOT_PO=3600; DHCP=1; NAPRAWA_START=300
    RELAY_ADDRESS=""; TRASY=""; T_PING=""
}
# Przebiegi petli od $1 do $2 (wlacznie) co $3 s (domyslnie POLL=10): tylko
# czesc sieciowa przebiegu
petla() {
    _u="$1"
    while [ "$_u" -le "$2" ]; do
        T_UP="$_u"; up="$_u"
        siec_brak_krok
        naprawa_krok
        _u=$((_u + ${3:-10}))
    done
}

# --- dhcp_od_nowa: prawdziwa funkcja, atrapy programow ----------------------------

kill()    { WYWOLANIA="$WYWOLANIA|kill $*"; }
killall() { WYWOLANIA="$WYWOLANIA|killall $*"; }
sleep()   { :; }
udhcpc()  { WYWOLANIA="$WYWOLANIA|udhcpc $*"; }
DHCP_PID="$T/udhcpc.eth0.pid"; echo 1188 > "$DHCP_PID"
dhcp_od_nowa
sprawdz "dhcp_od_nowa: stary klient z pidfile zabity" 'zawiera "$WYWOLANIA" "|kill 1188"'
sprawdz "dhcp_od_nowa: udhcpc -b (zostaje w tle i ponawia)" 'zawiera "$WYWOLANIA" "|udhcpc -R -b -p $DHCP_PID -i eth0"'
sprawdz "dhcp_od_nowa: bez -n (konczy klienta bez dzierzawy)" '! zawiera "$WYWOLANIA" " -n "'

# Od tej chwili akcje tylko zapisujemy
dhcp_od_nowa() { AKCJE="$AKCJE dhcp"; }
siec_od_nowa() { AKCJE="$AKCJE siec"; }
restart_boxa() { AKCJE="$AKCJE reboot"; ZD="$ZD|REBOOT $1"; }

# --- adres() ---------------------------------------------------------------------

od_nowa
T_IP_ADDR="$ADRES_OK"
sprawdz "adres: zwykly adres z DHCP" '[ "$(adres)" = 192.168.3.11/24 ]'
T_IP_ADDR="$ADRES_BRAK"
sprawdz "adres: brak inet = pusto" '[ -z "$(adres)" ]'
RELAY_ADDRESS=192.168.50.2/24
T_IP_ADDR="$ADRES_BRAK
    inet 192.168.50.2/24 scope global eth0"
sprawdz "adres: sam RELAY_ADDRESS to nie siec" '[ -z "$(adres)" ]'
T_IP_ADDR="$ADRES_BRAK
    inet 192.168.50.2/24 scope global eth0
    inet 192.168.1.41/24 brd 192.168.1.255 scope global eth0"
sprawdz "adres: RELAY_ADDRESS pominiety, adres z DHCP znaleziony" '[ "$(adres)" = 192.168.1.41/24 ]'

# --- DHCP=auto -------------------------------------------------------------------

INTERFACES="$T/interfaces"
printf '# automatically generated by enigma 2\nauto lo\niface lo inet loopback\n\nauto eth0\niface eth0 inet dhcp\nhwaddress ether 00:03:91:8d:bb:04\n' > "$INTERFACES"
T_DHCP_DZIALA=0
sprawdz "dhcp_auto: klient sie poddal, interfaces mowi dhcp = DHCP" 'dhcp_auto'
printf 'auto eth0\niface eth0 inet static\n  address 192.168.1.41\n' > "$INTERFACES"
sprawdz "dhcp_auto: interfaces static i brak klienta = statyczny" '! dhcp_auto'
T_DHCP_DZIALA=1
sprawdz "dhcp_auto: dzialajacy klient wygrywa" 'dhcp_auto'
T_DHCP_DZIALA=0
printf 'iface eth1 inet dhcp\niface eth0 inet static\n' > "$INTERFACES"
sprawdz "dhcp_auto: dhcp na innym interfejsie sie nie liczy" '! dhcp_auto'
printf '  iface   eth0  inet  dhcp\n' > "$INTERFACES"
sprawdz "dhcp_auto: wciecia i spacje" 'dhcp_auto'
rm -f "$INTERFACES"
sprawdz "dhcp_auto: brak pliku = statyczny" '! dhcp_auto'

# --- Z prawdziwymi adres() i brama() ----------------------------------------------

od_nowa
T_IP_ADDR="$ADRES_OK"; T_IP_ROUTE="$TRASA_BEZ_DEFAULT"
petla 60 360
sprawdz "adres bez trasy default to tez brak" 'zawiera "$ZD" "SIEC-BRAK adres 192.168.3.11/24 na eth0, brama BRAK od 300s" && [ "$AKCJE" = " dhcp" ]'
T_IP_ROUTE="$TRASA_OK"
petla 370 370
sprawdz "trasa wrocila: SIEC-OK" 'zawiera "$ZD" "SIEC-OK adres 192.168.3.11/24, brama 192.168.3.1"'

# Dalej szybkie atrapy - awk z prawdziwych to setki uruchomien programu
adres() { case "$T_IP_ADDR" in *"inet 192.168.3.11/24"*) echo 192.168.3.11/24 ;; esac; }
brama() { case "$T_IP_ROUTE" in *"default via 192.168.3.1 "*) echo 192.168.3.1 ;; esac; }

# --- SIEC-BRAK w standby, DHCP -----------------------------------------------------

od_nowa
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 350
sprawdz "przed SIEC_BRAK_PO nic" '[ -z "$ZD$AKCJE" ]'
petla 360 360
sprawdz "po SIEC_BRAK_PO: SIEC-BRAK" 'zawiera "$ZD" "SIEC-BRAK adres BRAK na eth0, brama BRAK od 300s: dhcp=tak -> klient DHCP od nowa (naprawa 1)"'
sprawdz "po SIEC_BRAK_PO: klient DHCP od nowa" '[ "$AKCJE" = " dhcp" ]'
petla 370 650
sprawdz "limit SIEC_BRAK_CO: nic przez 300 s" '[ "$AKCJE" = " dhcp" ]'
petla 660 660
sprawdz "druga naprawa jak NAPRAWA: diagnoza i akcja" 'zawiera "$ZD" "SIEC-BRAK adres BRAK na eth0, brama BRAK od 600s: brama BRAK=NIE internet=NIE dhcp=NIE -> klient DHCP od nowa (naprawa 2)"'
sprawdz "druga naprawa: znow klient DHCP" '[ "$AKCJE" = " dhcp dhcp" ]'
sprawdz "SIEC-BRAK bez powiadomienia (i tak nie wyjdzie)" '[ -z "$zd_wazne" ]'

# Powrot sieci: SIEC-OK z powiadomieniem, mimo swiezego WEBIF
T_IP_ADDR="$ADRES_OK"; T_IP_ROUTE="$TRASA_OK"; DOMOTICZ=1
pow_inne="$((680 - 5))"
petla 680 680
sprawdz "SIEC-OK po powrocie" 'zawiera "$ZD" "SIEC-OK adres 192.168.3.11/24, brama 192.168.3.1 - box byl bez sieci 10 min (od 07:52), napraw: 2"'
sprawdz "SIEC-OK jako wazne" '[ "$zd_wazne" = SIEC-OK ]'
po_przebiegu
sprawdz "SIEC-OK na telefon mimo WEBIF sprzed 5 s" 'zawiera "$POW" "|test: box byl bez sieci, juz ja ma#test, 07:52:00: dekoder w standby - SIEC-OK: adres 192.168.3.11/24"'
sprawdz "stan wyzerowany" '[ "$sb_zgl" -eq 0 ] && [ -z "$sb_od" ] && [ "$sb_napraw" -eq 0 ]'
_przed="$ZD"
petla 690 2000 50
sprawdz "z siecia dalej nic" '[ "$ZD" = "$_przed" ] && [ "$AKCJE" = " dhcp dhcp" ]'
DOMOTICZ=0

# Domoticz nie odpowiada przy SIEC-OK - raport() ponowi
od_nowa; DOMOTICZ=1; T_DZ_RC=1
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 360
T_IP_ADDR="$ADRES_OK"; T_IP_ROUTE="$TRASA_OK"
petla 370 370
po_przebiegu
sprawdz "SIEC-OK zalegle do ponowienia" '[ "$zal_temat" = "test: box byl bez sieci, juz ja ma" ]'
T_DZ_RC=0; DOMOTICZ=0

# --- Krotki brak, bez DHCP, bez trasy, wylaczone -----------------------------------

od_nowa
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 300
T_IP_ADDR="$ADRES_OK"; T_IP_ROUTE="$TRASA_OK"
petla 310 400
sprawdz "brak krotszy niz SIEC_BRAK_PO: nic, bez SIEC-OK" '[ -z "$ZD$AKCJE" ]'
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 410 700
sprawdz "kolejny brak liczony od nowa" '[ -z "$ZD$AKCJE" ]'
petla 710 710
sprawdz "kolejny brak po SIEC_BRAK_PO" '[ "$AKCJE" = " dhcp" ]'

od_nowa; DHCP=0
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 360
sprawdz "bez DHCP pierwsza akcja: restart sieci" '[ "$AKCJE" = " siec" ] && zawiera "$ZD" "dhcp=statyczny -> restart sieci (naprawa 1)"'

od_nowa; SIEC_BRAK_PO=0
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 5000 100
sprawdz "SIEC_BRAK_PO=0 wylacza kontrole" '[ -z "$ZD$AKCJE" ]'

# --- Restart boxa po REBOOT_PO -----------------------------------------------------

od_nowa; REBOOT_PO=900
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 950
sprawdz "przed REBOOT_PO dwie naprawy" '[ "$AKCJE" = " dhcp dhcp" ]'
petla 960 960
sprawdz "po REBOOT_PO restart boxa" '[ "$AKCJE" = " dhcp dhcp reboot" ] && zawiera "$ZD" "REBOOT adres BRAK na eth0, brama BRAK od 900s"'

od_nowa; REBOOT_PO=0
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 3660 30
sprawdz "REBOOT_PO=0: bez restartu, naprawy co SIEC_BRAK_CO" '! zawiera "$AKCJE" reboot && [ "$(ile "$AKCJE" dhcp)" -eq 12 ]'

# --- NAPRAWA nie dubluje SIEC-BRAK -----------------------------------------------

# Tuner pracuje, zaden czytnik nie jest polaczony od up=400, sieci brak od 60
od_nowa
T_IP_ADDR="$ADRES_BRAK"; T_IP_ROUTE=""
petla 60 350
czyt_od=350; czyt_zgloszony=1; czyt_ok=0; tuner=1
petla 360 360
sprawdz "SIEC-BRAK pierwszy, NAPRAWA czeka" '[ "$AKCJE" = " dhcp" ] && ! zawiera "$ZD" NAPRAWA'
petla 370 1000 30
sprawdz "przy SIEC-BRAK NAPRAWA nic nie robi" '! zawiera "$ZD" NAPRAWA && [ "$AKCJE" = " dhcp dhcp dhcp" ]'

# Bez SIEC-BRAK (adres i trasa sa) NAPRAWA dziala jak dotad
od_nowa
T_IP_ADDR="$ADRES_OK"; T_IP_ROUTE="$TRASA_OK"
czyt_od=300; czyt_zgloszony=1; czyt_ok=0; tuner=1
petla 300 340
sprawdz "z adresem NAPRAWA jak dotad" 'zawiera "$ZD" "NAPRAWA czytnik od 40s: brama 192.168.3.1=NIE internet=NIE dhcp=NIE -> klient DHCP od nowa" && [ "$AKCJE" = " dhcp" ] && ! zawiera "$ZD" SIEC-BRAK'

echo "testy: $ok ok, $zle zle"
[ "$zle" -eq 0 ]
